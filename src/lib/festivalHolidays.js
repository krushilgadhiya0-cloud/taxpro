// Helper to retrieve all active holidays & custom notices merged
export const getUnifiedHolidayNotices = () => {
  let customNotices = [];
  try {
    const raw = localStorage.getItem('taxpro_firm_notices');
    if (raw) customNotices = JSON.parse(raw);
  } catch (e) {}

  let removedIds = [];
  try {
    const rawRemoved = localStorage.getItem('taxpro_removed_holidays');
    if (rawRemoved) removedIds = JSON.parse(rawRemoved);
  } catch (e) {}

  const removedSet = new Set(removedIds);

  // Filter master festival holidays by exclusions
  const activeFestivalHolidays = MASTER_FESTIVAL_HOLIDAYS.filter(h => !removedSet.has(h.id));

  // Map custom notices to ensure uniqueness
  const customMap = new Map();
  customNotices.forEach(n => {
    if (!removedSet.has(n.id)) {
      customMap.set(n.id, n);
    }
  });

  // Combine custom notices with master festival holidays
  const combined = [...customNotices.filter(n => !removedSet.has(n.id))];
  activeFestivalHolidays.forEach(h => {
    if (!customMap.has(h.id)) {
      combined.push(h);
    }
  });

  return combined;
};

// Remove holiday notice (available to Admins & Managers)
export const deleteHolidayNotice = (id) => {
  let removedIds = [];
  try {
    const rawRemoved = localStorage.getItem('taxpro_removed_holidays');
    if (rawRemoved) removedIds = JSON.parse(rawRemoved);
  } catch (e) {}

  if (!removedIds.includes(id)) {
    removedIds.push(id);
    localStorage.setItem('taxpro_removed_holidays', JSON.stringify(removedIds));
  }

  // Also remove from custom notices if present
  try {
    const raw = localStorage.getItem('taxpro_firm_notices');
    if (raw) {
      const parsed = JSON.parse(raw).filter(n => n.id !== id);
      localStorage.setItem('taxpro_firm_notices', JSON.stringify(parsed));
    }
  } catch (e) {}

  const updated = getUnifiedHolidayNotices();
  window.dispatchEvent(new CustomEvent('taxpro_notices_updated', { detail: updated }));
  return updated;
};

// Add new custom holiday notice
export const saveCustomHolidayNotice = (newNotice) => {
  let customNotices = [];
  try {
    const raw = localStorage.getItem('taxpro_firm_notices');
    if (raw) customNotices = JSON.parse(raw);
  } catch (e) {}

  const updated = [newNotice, ...customNotices.filter(n => n.id !== newNotice.id)];
  localStorage.setItem('taxpro_firm_notices', JSON.stringify(updated));

  // If was previously removed, un-remove it
  try {
    const rawRemoved = localStorage.getItem('taxpro_removed_holidays');
    if (rawRemoved) {
      const filteredRemoved = JSON.parse(rawRemoved).filter(id => id !== newNotice.id);
      localStorage.setItem('taxpro_removed_holidays', JSON.stringify(filteredRemoved));
    }
  } catch (e) {}

  const fullList = getUnifiedHolidayNotices();
  window.dispatchEvent(new CustomEvent('taxpro_notices_updated', { detail: fullList }));
  return fullList;
};

// Restore / Un-remove a previously deleted holiday
export const restoreHolidayNotice = (id) => {
  try {
    const rawRemoved = localStorage.getItem('taxpro_removed_holidays');
    if (rawRemoved) {
      const filtered = JSON.parse(rawRemoved).filter(removedId => removedId !== id);
      localStorage.setItem('taxpro_removed_holidays', JSON.stringify(filtered));
    }
  } catch (e) {}

  const updated = getUnifiedHolidayNotices();
  window.dispatchEvent(new CustomEvent('taxpro_notices_updated', { detail: updated }));
  return updated;
};

// Retrieve all master + custom holidays with their removed status
export const getAllMasterAndCustomHolidays = () => {
  let customNotices = [];
  try {
    const raw = localStorage.getItem('taxpro_firm_notices');
    if (raw) customNotices = JSON.parse(raw);
  } catch (e) {}

  let removedIds = [];
  try {
    const rawRemoved = localStorage.getItem('taxpro_removed_holidays');
    if (rawRemoved) removedIds = JSON.parse(rawRemoved);
  } catch (e) {}

  const removedSet = new Set(removedIds);
  const customMap = new Map();
  customNotices.forEach(n => {
    customMap.set(n.id, n);
  });

  const list = [];
  MASTER_FESTIVAL_HOLIDAYS.forEach(h => {
    list.push({
      ...h,
      isRemoved: removedSet.has(h.id)
    });
  });

  customNotices.forEach(n => {
    if (!list.some(item => item.id === n.id)) {
      list.push({
        ...n,
        isRemoved: removedSet.has(n.id)
      });
    }
  });

  return list.sort((a, b) => (a.holidayDate || a.date || '').localeCompare(b.holidayDate || b.date || ''));
};
